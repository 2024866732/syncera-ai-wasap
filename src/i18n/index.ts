export function t(key: string, lang: Lang = 'en'): string {
  const entry = dict[key]
  if (!entry) return key
  return entry[lang] || entry.en || key
}

export function useT(): (key: string, params?: Record<string,string|number>) => string {
  const lang = (useStore(s => s.appSettings['app_language']) || 'ms') as Lang
  return (key: string, params?: Record<string, string|number>) => {
    let str = t(key, lang)
    if (params) for (const [k, v] of Object.entries(params)) str = str.replace(`{${k}}`, String(v))
    return str
  }
}

export function getActiveLang(): Lang {
  try {
    const stored = (useStore.getState().appSettings['app_language'] || 'ms') as Lang
    if (['en','ms'].includes(stored)) return stored
  } catch {}
  return 'ms'
}

export function applyLangAttr(lang: Lang) {
  document.documentElement.lang = lang === 'zh' ? 'zh-MY' : lang
}
